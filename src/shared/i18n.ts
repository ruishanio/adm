export type MessageKey = keyof typeof english;
/**
 * 首次启动或旧版 system 偏好迁移时识别系统首选语言；已保存的显式语言始终优先。
 * 未提供对应翻译的语言（包括繁体中文）回退英语，不使用次选语言替代系统首选。
 */
export function resolveLocale(
  value?: string,
  languages: readonly string[] = typeof navigator === 'undefined' ? ['en'] : [navigator.language],
): Locale {
  if (value === 'zh-CN' || value === 'en') return value;
  const primary = (languages[0] || '').replaceAll('_', '-');
  if (/^zh(?:-Hans(?:-|$)|-(?:CN|SG)$|$)/i.test(primary)) return 'zh-CN';
  return 'en';
}
const preference = ref<LanguagePreference>(resolveLocale());
export const language = readonly(preference);
export const locale = language;
export function setLanguage(value: LanguagePreference) {
  preference.value = value;
}
/** 翻译界面文案并替换具名参数；路径、包名和设备名称只能作为参数传入，不能用作翻译键。 */
export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  const text = locale.value === 'en' ? english[key] : key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}
export function initializeLanguage() {
  watch(
    locale,
    (value) => {
      document.documentElement.lang = value;
    },
    { immediate: true },
  );
}
